// 各厂商默认地域（未配置时回退到列表首项）
export const DEFAULT_REGIONS = {
  aliyun: 'cn-hangzhou',
  tencent: 'ap-guangzhou',
  aws: 'us-east-1',
  huawei: 'cn-north-4',
}

const FALLBACK_VENDOR = 'aliyun'

export function regionOptions(vendor) {
  const list = VENDOR_REGIONS[vendor] || VENDOR_REGIONS[FALLBACK_VENDOR]
  return list.map((value) => ({ value, label: value }))
}

export function defaultRegion(vendor) {
  if (DEFAULT_REGIONS[vendor]) return DEFAULT_REGIONS[vendor]
  const list = VENDOR_REGIONS[vendor] || VENDOR_REGIONS[FALLBACK_VENDOR]
  return list[0]
}
